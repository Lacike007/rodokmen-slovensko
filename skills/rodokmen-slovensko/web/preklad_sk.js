// Vzory pre texty s číslami a menami.
const GEN = (pra) => ['rodičia', 'starí rodičia', 'prastarí rodičia'][pra] ?? `${'pra'.repeat(pra - 1)}starí rodičia`;
const PRIBUZNY = { 'otec': 'otec', 'matka': 'matka', 'dědeček': 'starý otec', 'babička': 'stará mama',
  'pradědeček': 'prastarý otec', 'prababička': 'prastará mama', 'výchozí osoba rodokmenu': 'východisková osoba rodokmeňa' };
export const VZORY = [
  [/^(\d+) předků · začíná u (.+)$/, (_, n, k) => `${n} predkov · začína pri: ${k}`],
  [/^Rodokmen pokračuje: (\d+) dalších předků$/, (_, n) => `Rodokmeň pokračuje: ${n} ďalších predkov`],
  [/^(\d+) rodů$/, (_, n) => `${n} rodov`],
  [/^(\d+)\. generace \(((?:pra)*)rodiče\)$/, (_, g, p) => `${g}. generácia (${GEN(p.length / 3)})`],
  [/^Výřez zápisu: (.+)$/, (_, t) => `Výrez zápisu: ${t}`],
  [/^– přímý předek \((.+)\)$/, (_, r) => `– priamy predok (${PRIBUZNY[r] ?? r})`],
  [/^neznámý otec a (.+)$/, (_, m) => `neznámy otec a ${m}`],
  [/^Všech (\d+) zápisů, na kterých rodokmen stojí – chronologicky\. U každého je výřez snímku s vyznačeným místem, plné rozlišení a odkaz do archivu\. Co v matrikách zatím chybí nebo si odporuje, najdete v přehledu$/,
    (_, n) => `Všetkých ${n} zápisov, na ktorých rodokmeň stojí – chronologicky. Pri každom je výrez snímky s vyznačeným miestom, plné rozlíšenie a odkaz do archívu. Čo v matrikách zatiaľ chýba alebo si odporuje, nájdete v prehľade`],
  [/^Pro přiblížení mapy držte (.+) a točte kolečkem$/, (_, k) => `Na priblíženie mapy držte ${k} a točte kolieskom`],
  [/^Přečíst: (.+)$/, (_, t) => `Prečítať: ${t}`],
  [/^(.+) · rodinný web, neveřejný$/, (_, z) => `${PRESNE[z] ?? z} · rodinný web, neverejný`],
  [/^Konvence: každý řádek = jedno hledání, i neúspěšné\.(.*)$/s, () => PRESNE['Konvence: každý řádek = jedno hledání, i neúspěšné. Negativní výsledek vždy s rozsahem (které roky, které snímky). „snímek“ = pořadové číslo skenu na portálu archivu.']],
];

export function prelozText(s) {
  const t = s.trim();
  if (!t) return s;
  let out = PRESNE[t];
  if (out === undefined) {
    for (const [re, fn] of VZORY) if (re.test(t)) { out = t.replace(re, fn); break; }
  }
  return out === undefined ? s : s.replace(t, out);
}
